from markupsafe import Markup

from odoo import _, api, fields, models
from odoo.exceptions import UserError

from .amc_contract import _CONTRACT_MARKER, _marked

BILLING_LINE_STATES = [
    ('planned', 'Planned'),
    ('released', 'To Invoice'),
    ('cancelled', 'Cancelled'),
]


class AmcBillingLine(models.Model):
    """AMC billing schedule (phase A5; AMC-B09 / G01 / G03 / G04, approved B4a / B4d): one line
    per billing period of the contract's Billing Plan. Releasing a line delivers one unit on
    the AMC Sales Order line, so the period is invoiced with the standard Sales invoicing
    (Create Invoice); nothing is posted or paid automatically. Upfront / periodic periods are
    released on their billing date, Per Preventive Visit periods when the visit is consumed."""
    _name = 'amc.billing.line'
    _description = 'AMC Billing Schedule Line'
    _order = 'contract_id, sequence, id'

    contract_id = fields.Many2one('amc.contract', string='AMC Contract', required=True,
                                  readonly=True, ondelete='cascade', index=True)
    company_id = fields.Many2one(related='contract_id.company_id', store=True, index=True)
    currency_id = fields.Many2one(related='contract_id.currency_id')
    partner_id = fields.Many2one(related='contract_id.partner_id', store=True)
    sequence = fields.Integer(string='Period', readonly=True)
    sale_line_id = fields.Many2one('sale.order.line', string='Sales Order Line', readonly=True,
                                   ondelete='restrict', index=True)
    amount = fields.Monetary(string='Amount (Untaxed)', readonly=True)
    date = fields.Date(string='Billing Date', readonly=True, index=True,
                       help="In advance: the period start; in arrears: the period end. Per "
                            "Preventive Visit: when the visit is completed.")
    period_start = fields.Date(string='Period Start', readonly=True)
    period_end = fields.Date(string='Period End', readonly=True)
    visit_id = fields.Many2one('amc.contract.visit', string='Preventive Visit', readonly=True,
                               ondelete='set null')
    state = fields.Selection(BILLING_LINE_STATES, string='Status', default='planned',
                             required=True, readonly=True, index=True)
    released_date = fields.Date(string='Released On', readonly=True)
    invoiced = fields.Boolean(string='Invoiced', compute='_compute_invoiced',
                              help="The Sales Order line has invoiced at least this period.")

    @api.depends('state', 'sale_line_id.qty_invoiced', 'sequence')
    def _compute_invoiced(self):
        for line in self:
            if line.state != 'released' or not line.sale_line_id:
                line.invoiced = False
                continue
            released = line.contract_id.billing_line_ids.filtered(
                lambda other: other.sale_line_id == line.sale_line_id
                and other.state == 'released').sorted('sequence')
            rank = list(released).index(line) + 1
            line.invoiced = line.sale_line_id.qty_invoiced >= rank

    @api.model_create_multi
    def create(self, vals_list):
        if self.env.context.get('amc_contract_marker') is not _CONTRACT_MARKER:
            raise UserError(_("The AMC billing schedule is generated by the contract."))
        return super().create(vals_list)

    def write(self, vals):
        if self.env.context.get('amc_contract_marker') is not _CONTRACT_MARKER:
            raise UserError(_("The AMC billing schedule is changed only by the contract."))
        return super().write(vals)

    @api.ondelete(at_uninstall=False)
    def _unlink_except_released(self):
        if self.env.context.get('amc_contract_marker') is not _CONTRACT_MARKER:
            raise UserError(_("The AMC billing schedule is kept for the audit history."))
        if self.filtered(lambda line: line.state == 'released'):
            raise UserError(_("Released AMC billing periods cannot be deleted."))

    def _amc_release(self, date=None):
        """Release planned periods once (AMC-G03): +1 delivered on the Sales Order line (the
        lines of AMC quotations are locked for users; the contract marker writes them)."""
        date = date or fields.Date.context_today(self)
        for line in self.filtered(lambda line: line.state == 'planned'):
            sale_line = line.sale_line_id.sudo()
            if not sale_line or sale_line.order_id.state != 'sale':
                raise UserError(_("AMC billing period %(period)s of %(contract)s has no "
                                  "confirmed Sales Order line.", period=line.sequence,
                                  contract=line.contract_id.name))
            released = len(line.contract_id.billing_line_ids.filtered(
                lambda other: other.sale_line_id == line.sale_line_id
                and other.state == 'released'))
            if released + 1 > sale_line.product_uom_qty:
                raise UserError(_("AMC billing period %(period)s of %(contract)s exceeds the "
                                  "ordered periods.", period=line.sequence,
                                  contract=line.contract_id.name))
            _marked(sale_line).write({'qty_delivered': released + 1})
            _marked(line).write({'state': 'released', 'released_date': date})
            line.contract_id._message_log(body=Markup('<p>%s</p>') % _(
                "Billing period %(period)s released for invoicing: %(amount)s (%(order)s).",
                period=line.sequence, amount=line.currency_id.format(line.amount),
                order=sale_line.order_id.name))
        return True
